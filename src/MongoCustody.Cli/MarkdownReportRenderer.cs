using System.Globalization;
using System.Text;
using MongoCustody.Core.Models;

namespace MongoCustody.Cli;

/// <summary>
/// Renders an <see cref="AuditReport"/> to a Markdown string.
/// No file I/O — the caller writes the result to disk.
/// </summary>
internal static class MarkdownReportRenderer
{
    public static string Render(AuditReport report)
    {
        var sb = new StringBuilder(4096);

        AppendHeader(sb, report);
        AppendSummaryTable(sb, report.Summary);

        if (!report.IsSingleRestoreMode && report.Backups.Count > 0)
            AppendBackupsSection(sb, report.Backups);

        AppendRestoresSection(sb, report.Restores);
        AppendFooter(sb);

        return sb.ToString();
    }

    // ------------------------------------------------------------------ //

    private static void AppendHeader(StringBuilder sb, AuditReport report)
    {
        if (report.IsSingleRestoreMode)
        {
            var restoreId = report.Restores.Count > 0
                ? report.Restores[0].Record.RestoreId
                : "unknown";
            sb.AppendLine($"# MongoCustody Restore Audit Report");
            sb.AppendLine();
            sb.AppendLine($"**Restore ID:** `{restoreId}`");
        }
        else
        {
            sb.AppendLine("# MongoCustody Audit Report");
            sb.AppendLine();
            sb.AppendLine($"**Period:** {Fmt(report.From)} – {Fmt(report.To)}");
            sb.AppendLine($"**Database:** {report.DatabaseFilter ?? "all databases"}");
        }

        sb.AppendLine($"**Generated:** {FmtLong(report.GeneratedAtUtc)}");
        sb.AppendLine($"**Generated by:** {EscapeMd(report.GeneratedBy)}");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();
    }

    private static void AppendSummaryTable(StringBuilder sb, AuditSummary s)
    {
        sb.AppendLine("## Executive Summary");
        sb.AppendLine();
        sb.AppendLine("| Metric | Value |");
        sb.AppendLine("|---|---|");

        if (s.BackupsCompleted + s.BackupsFailed > 0)
        {
            sb.AppendLine($"| Full backups completed | {s.BackupsCompleted:N0} |");
            sb.AppendLine($"| Full backups failed | {s.BackupsFailed:N0} |");
            sb.AppendLine($"| Total collections backed up | {s.TotalCollectionsBacked:N0} |");
            sb.AppendLine($"| Total documents backed up | {s.TotalDocumentsBacked:N0} |");
        }

        sb.AppendLine($"| Restore operations completed | {s.RestoresCompleted:N0} |");
        sb.AppendLine($"| Restore operations failed | {s.RestoresFailed:N0} |");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();
    }

    private static void AppendBackupsSection(
        StringBuilder sb,
        IReadOnlyList<BackupRecord> backups)
    {
        sb.AppendLine("## Full Backup Activity");
        sb.AppendLine();

        foreach (var b in backups)
        {
            var heading = $"{FmtLong(b.CompletedAtUtc)} — {b.DatabaseName} [COMPLETED]";
            sb.AppendLine($"### {heading}");
            sb.AppendLine();

            sb.AppendLine("| Field | Value |");
            sb.AppendLine("|---|---|");
            sb.AppendLine($"| Backup ID | `{b.BackupId}` |");
            sb.AppendLine($"| Quarter | {b.QuarterLabel} |");
            sb.AppendLine($"| Folder | `{EscapeMd(b.BackupFolder)}` |");
            sb.AppendLine($"| Collections | {b.Collections.Count:N0} |");
            sb.AppendLine($"| Total documents | {b.Collections.Sum(c => (long)c.TotalDocuments):N0} |");
            if (!string.IsNullOrEmpty(b.TriggeredBy))
                sb.AppendLine($"| Triggered by | {EscapeMd(b.TriggeredBy)} |");
            if (!string.IsNullOrEmpty(b.CorrelationId))
                sb.AppendLine($"| Correlation ID | `{b.CorrelationId}` |");
            sb.AppendLine();

            if (b.Collections.Count > 0)
            {
                sb.AppendLine("| Collection | Documents | Chunks |");
                sb.AppendLine("|---|---|---|");
                foreach (var c in b.Collections)
                    sb.AppendLine($"| {EscapeMd(c.CollectionName)} | {c.TotalDocuments:N0} | {c.ChunkCount:N0} |");
                sb.AppendLine();
            }

            sb.AppendLine("---");
            sb.AppendLine();
        }
    }

    private static void AppendRestoresSection(
        StringBuilder sb,
        IReadOnlyList<RestoreAuditEntry> restores)
    {
        if (restores.Count == 0) return;

        sb.AppendLine("## Restore Activity");
        sb.AppendLine();

        foreach (var entry in restores)
        {
            var r = entry.Record;
            var heading =
                $"{FmtLong(r.RequestedAtUtc)} — {r.DatabaseName} → {r.TargetDatabaseName} [{r.Status}]";
            sb.AppendLine($"### {heading}");
            sb.AppendLine();

            sb.AppendLine("| Field | Value |");
            sb.AppendLine("|---|---|");
            sb.AppendLine($"| Restore ID | `{r.RestoreId}` |");
            sb.AppendLine($"| Source database | {EscapeMd(r.DatabaseName)} |");
            sb.AppendLine($"| Target database | {EscapeMd(r.TargetDatabaseName)} |");
            sb.AppendLine($"| Requested restore point | {FmtLong(r.TargetDate)} |");
            sb.AppendLine($"| Status | {r.Status} |");
            if (r.CompletedAtUtc.HasValue)
                sb.AppendLine($"| Completed | {FmtLong(r.CompletedAtUtc.Value)} |");
            if (!string.IsNullOrEmpty(r.RequestedBy))
                sb.AppendLine($"| Requested by | {EscapeMd(r.RequestedBy)} |");
            if (!string.IsNullOrEmpty(r.ApprovedBy))
                sb.AppendLine($"| Approved by | {EscapeMd(r.ApprovedBy)} |");
            if (!string.IsNullOrEmpty(r.Reason))
                sb.AppendLine($"| Reason | {EscapeMd(r.Reason)} |");
            if (!string.IsNullOrEmpty(r.CorrelationId))
                sb.AppendLine($"| Correlation ID | `{r.CorrelationId}` |");
            if (!string.IsNullOrEmpty(r.FailureReason))
                sb.AppendLine($"| Failure reason | {EscapeMd(r.FailureReason)} |");
            sb.AppendLine();

            if (entry.ChainSteps.Count > 0)
            {
                AppendChainNarrative(sb, r, entry.ChainSteps);
            }

            sb.AppendLine("---");
            sb.AppendLine();
        }
    }

    private static void AppendChainNarrative(
        StringBuilder sb,
        RestoreRecord r,
        IReadOnlyList<RestoreChainStep> steps)
    {
        sb.AppendLine("#### Restore Chain Applied");
        sb.AppendLine();
        sb.AppendLine(
            $"To reach the requested restore point of **{FmtLong(r.TargetDate)}**, " +
            $"the following backups were applied in sequence:");
        sb.AppendLine();

        sb.AppendLine("| Step | Type | Backup date | Documents written |");
        sb.AppendLine("|---|---|---|---|");
        foreach (var step in steps)
        {
            var docNote = step.BackupDate == DateTimeOffset.MinValue
                ? "manifest unavailable"
                : step.IsBaselineInsert
                    ? $"{step.DocumentsWritten:N0} inserted"
                    : $"{step.DocumentsWritten:N0} upserted";

            var dateStr = step.BackupDate == DateTimeOffset.MinValue
                ? "unknown"
                : FmtLong(step.BackupDate);

            sb.AppendLine(
                $"| {step.StepNumber} | {step.BackupType} | {dateStr} | {docNote} |");
        }

        sb.AppendLine();

        // Narrative sentence
        var baseline = steps[0];
        var following = steps.Skip(1).ToList();

        if (baseline.BackupDate != DateTimeOffset.MinValue)
        {
            var baselineDate = baseline.BackupDate.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
            var followingDocs = following.Sum(s => s.DocumentsWritten);

            if (following.Count == 0)
            {
                sb.AppendLine(
                    $"The full backup from **{baselineDate}** provided the complete " +
                    $"restore baseline ({baseline.DocumentsWritten:N0} documents inserted).");
            }
            else
            {
                var chainType = following.All(s => s.BackupType == BackupType.Incremental)
                    ? "incremental backup"
                    : "backup";
                var plural = following.Count == 1 ? $"1 subsequent {chainType} was" : $"{following.Count} subsequent {chainType}s were";

                sb.AppendLine(
                    $"The full backup from **{baselineDate}** provided the baseline " +
                    $"({baseline.DocumentsWritten:N0} documents inserted). " +
                    $"{plural} replayed to advance to the requested point in time, " +
                    $"updating a total of {followingDocs:N0} documents.");
            }
        }

        sb.AppendLine();
    }

    private static void AppendFooter(StringBuilder sb)
    {
        sb.AppendLine("## Notes");
        sb.AppendLine();
        sb.AppendLine(
            "- All backup manifests contain SHA-256 per-collection hash values " +
            "for integrity verification.");
        sb.AppendLine(
            "- Restore operations record the requesting and approving principal " +
            "in the audit trail before any data is written to the target database.");
        sb.AppendLine(
            "- This report was generated from immutable Blob Storage records " +
            "and reflects the state of all backup and restore metadata at generation time.");
    }

    // ------------------------------------------------------------------ //
    //  Formatting helpers
    // ------------------------------------------------------------------ //

    private static string Fmt(DateTimeOffset dt)
        => dt.UtcDateTime.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);

    private static string FmtLong(DateTimeOffset dt)
        => dt.UtcDateTime.ToString("yyyy-MM-dd HH:mm UTC", CultureInfo.InvariantCulture);

    private static string EscapeMd(string text)
        => text.Replace("|", "\\|");
}
